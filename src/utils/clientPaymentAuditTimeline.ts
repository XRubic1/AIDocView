export type PaymentAuditTone = 'neutral' | 'success' | 'warning' | 'error' | 'info'
export type PaymentAuditSource = 'carrier' | 'credyx'

export interface PaymentAuditTimelineEntry {
  id: string
  timestamp: string
  title: string
  detail: string
  tone: PaymentAuditTone
  /** Free-text notes vs status / payment activity (aligned with InvoiceDetailPanel). */
  kind: 'activity' | 'note'
  /** Left-edge color / type marker. */
  noteKind?: string
  /** Carrier vs Credyx authorship. */
  source?: PaymentAuditSource
  meta?: string
}

const METHOD_LABELS: Record<string, string> = {
  check: 'Check',
  wire: 'Wire',
  ach: 'ACH',
  credit_card: 'Card',
}

const NOTE_TITLES: Record<string, string> = {
  dispute: 'Dispute',
  client_note: 'Note',
  hold_reason: 'On Hold',
  approval: 'Approved',
  rejection: 'Rejected',
  note: 'Note',
}

function isFreeTextNote(type?: InvoiceNote['type']): boolean {
  return type === 'note' || type === 'client_note' || type == null
}

/**
 * Free-text notes generated by payment post / confirm flows.
 * These belong under the Payments tab, not Notes.
 */
export function isPaymentRelatedInvoiceNote(note: string, type?: InvoiceNote['type']): boolean {
  if (type === 'dispute' || type === 'hold_reason' || type === 'approval' || type === 'rejection') {
    return false
  }
  const text = note.toLowerCase()
  return (
    /payment confirmed by client|paid in full|invoice closed pending|payment of \$|posted —|short by|over by|receipt dispute|confirmed receiving|force.?confirm|remittance|short pay|shortfall|overpay|overpayment|chargeback|wire|ach\b|check #|credyx posted|funds moved|write-off|closed as uncollectable|was not confirmed/.test(
      text
    )
  )
}

/** Human category for payment-related free-text notes. */
export function getPaymentNoteCategoryTitle(note: string): string {
  const text = note.toLowerCase()

  if (/receipt dispute resolved/.test(text)) return 'Dispute Resolved'
  if (/receipt dispute|funds on hold/.test(text)) return 'Payment Dispute'
  // Combined write-off close note — confirmation half is handled by expandClosedUncollectableNote.
  if (/closed as uncollectable/.test(text)) return 'Write-off'
  if (/payment confirmed by client|paid in full|confirmed receiving/.test(text)) {
    return 'Payment Confirmation'
  }
  if (/credyx posted|please confirm receipt|please confirm within/.test(text)) {
    return /short payment correction/.test(text) ? 'Short Correction' : 'Payment Posted'
  }
  if (/invoice closed pending|payment of .+ posted/.test(text)) return 'Payment Posted'
  if (/was not confirmed|payment rejected|force.?confirm/.test(text)) return 'Payment Rejected'
  if (/funds moved/.test(text)) return 'Funds Moved'
  if (/write-off/.test(text)) return 'Write-off'
  if (/overpayment accepted|overpay|over by/.test(text)) return 'Overpayment'
  if (/short by|short pay|shortfall|short payment/.test(text)) return 'Short Payment'
  if (/remittance|wire|ach\b|check #|chargeback/.test(text)) return 'Remittance'

  return 'Payment'
}

/** Legacy combined close note: "Closed as uncollectable — received $X, write-off $Y. reason" */
const CLOSED_UNCOLLECTABLE_RE =
  /^Closed as uncollectable\s*[—\-]\s*received\s+(\$[\d,]+(?:\.\d{2})?)\s*[,;]\s*write-off\s+(\$[\d,]+(?:\.\d{2})?)\s*[,;.]?\s*(.*)$/i

export function isClosedUncollectableNote(note: string): boolean {
  return /^Closed as uncollectable/i.test(note.trim())
}

/**
 * Split a combined uncollectable-close note into Payment Confirmation + Write-off rows.
 * Returns null when the note is not that combined form.
 */
export function expandClosedUncollectableNote(
  note: InvoiceNote
): PaymentAuditTimelineEntry[] | null {
  const raw = note.note.trim()
  if (!isClosedUncollectableNote(raw)) return null

  const match = raw.match(CLOSED_UNCOLLECTABLE_RE)
  if (!match) {
    const soft = raw.match(
      /received\s+(\$[\d,]+(?:\.\d{2})?).*?write-off\s+(\$[\d,]+(?:\.\d{2})?)\s*[,;.]?\s*(.*)$/i
    )
    if (!soft) return null
    return buildClosedUncollectableEntries(note, soft[1], soft[2], soft[3] ?? '')
  }

  return buildClosedUncollectableEntries(note, match[1], match[2], match[3] ?? '')
}

function buildClosedUncollectableEntries(
  note: InvoiceNote,
  receivedLabel: string,
  writeOffLabel: string,
  reason: string,
  source: PaymentAuditSource = 'carrier'
): PaymentAuditTimelineEntry[] {
  const meta = note.created_by?.trim() || undefined
  const baseMs = new Date(note.created_at).getTime()
  // Confirmation first (older), write-off second (newer) when sorted newest-first.
  const confirmAt = new Date(Number.isFinite(baseMs) ? baseMs : Date.now()).toISOString()
  const writeOffAt = new Date(
    (Number.isFinite(baseMs) ? baseMs : Date.now()) + 1000
  ).toISOString()
  const reasonPart = reason.trim().replace(/^[,;.]\s*/, '')

  return [
    {
      id: `note-${note.id}-confirm`,
      timestamp: confirmAt,
      title: 'Payment Confirmation',
      detail: `${receivedLabel} received`,
      tone: 'success',
      kind: 'activity',
      noteKind: 'payment',
      source,
      meta,
    },
    {
      id: `note-${note.id}-writeoff`,
      timestamp: writeOffAt,
      title: 'Write-off',
      detail: reasonPart
        ? `${writeOffLabel} — ${reasonPart}`
        : `${writeOffLabel} written off`,
      tone: 'warning',
      kind: 'activity',
      noteKind: 'payment',
      source,
      meta,
    },
  ]
}

/**
 * System-generated notes that mirror payment / dispute lifecycle events.
 * Prefer the structured payment activity entry so the timeline shows one row, not two.
 */
export function isRedundantPaymentLifecycleNote(note: string, type?: InvoiceNote['type']): boolean {
  const text = note.toLowerCase()

  // Typed dispute note written alongside payment.dispute on open.
  if (type === 'dispute' && /payment receipt dispute/.test(text)) return true

  return (
    /payment receipt dispute resolved/.test(text) ||
    /payment receipt dispute:/.test(text) ||
    /credyx posted .+ — please confirm/.test(text) ||
    /credyx posted short payment correction/.test(text) ||
    /please confirm receipt within \d+ days/.test(text) ||
    /invoice closed pending confirmation/.test(text) ||
    /payment of .+ posted(?:\.|$)/.test(text)
  )
}

/**
 * Same note list as InvoiceDetailPanel (client-visible history + hold/notes fallbacks).
 */
function getClientInvoiceNoteEntries(invoice: Invoice): InvoiceNote[] {
  const visible = clientVisibleNotes(invoice.notes_history)
  if (visible.length) {
    return [...visible].sort(
      (a, b) => new Date(b.created_at).getTime() - new Date(a.created_at).getTime()
    )
  }

  const fallback: InvoiceNote[] = []
  if (invoice.hold_reason) {
    fallback.push({
      id: 'hold-fallback',
      note: invoice.hold_reason,
      created_by: invoice.reviewed_by || 'Credyx',
      created_at: invoice.reviewed_at || invoice.updated_at || invoice.created_at,
      type: 'hold_reason',
    })
  }
  if (invoice.notes) {
    fallback.push({
      id: 'note-fallback',
      note: invoice.notes,
      created_by: invoice.reviewed_by || 'Credyx',
      created_at: invoice.created_at,
      type: 'note',
    })
  }
  return fallback
}

function noteTone(type?: InvoiceNote['type']): PaymentAuditTone {
  switch (type) {
    case 'approval':
      return 'success'
    case 'client_note':
      return 'info'
    case 'rejection':
    case 'dispute':
      return 'error'
    case 'hold_reason':
      return 'warning'
    default:
      return 'neutral'
  }
}

function noteSource(note: InvoiceNote): PaymentAuditSource {
  if (note.type === 'dispute') return 'carrier'
  if (note.type === 'client_note') {
    const by = note.created_by?.trim().toLowerCase() || ''
    // Admin/Credyx force-confirm notes are stored as client_note but are Credyx-authored.
    if (
      isPaymentRelatedInvoiceNote(note.note, note.type) &&
      (by === 'admin' || by.includes('credyx'))
    ) {
      return 'credyx'
    }
    return 'carrier'
  }
  return 'credyx'
}

/** Push invoice note using the same Notes vs Activity split as InvoiceDetailPanel. */
function pushInvoiceNote(entries: PaymentAuditTimelineEntry[], note: InvoiceNote) {
  // Lifecycle notes are already represented by payment / dispute activity rows.
  if (isRedundantPaymentLifecycleNote(note.note, note.type)) return

  // Combined write-off close → Payment Confirmation + Write-off (not one merged row).
  const expanded = expandClosedUncollectableNote(note)
  if (expanded) {
    const source = noteSource(note)
    for (const entry of expanded) {
      entries.push({ ...entry, source })
    }
    return
  }

  const typeKey = note.type ?? 'note'
  const paymentRelated =
    isFreeTextNote(note.type) && isPaymentRelatedInvoiceNote(note.note, note.type)

  const title = paymentRelated
    ? getPaymentNoteCategoryTitle(note.note)
    : (NOTE_TITLES[typeKey] ?? 'Update')

  let detail = note.note
  if (title === 'Payment Confirmation') {
    const receivedMatch =
      note.note.match(/(\$[\d,]+(?:\.\d{2})?)\s+received/i) ||
      note.note.match(/received\s+(\$[\d,]+(?:\.\d{2})?)/i)
    if (receivedMatch) detail = `${receivedMatch[1]} received`
  }

  entries.push({
    id: `note-${note.id}`,
    timestamp: note.created_at,
    title,
    detail,
    tone: paymentRelated ? (title === 'Payment Confirmation' ? 'success' : 'info') : noteTone(note.type),
    // Payment-related free text → payments tab; typed status → activity; else notes.
    kind: paymentRelated ? 'activity' : isFreeTextNote(note.type) ? 'note' : 'activity',
    noteKind: paymentRelated ? 'payment' : typeKey,
    source: noteSource(note),
    meta: note.created_by?.trim() || undefined,
  })
}

function paymentTone(status: Payment['status']): PaymentAuditTone {
  switch (status) {
    case 'confirmed':
      return 'success'
    case 'reversed':
    case 'rejected':
      return 'error'
    case 'disputed':
    case 'awaiting_receipt':
    case 'pending':
      return 'warning'
    default:
      return 'info'
  }
}

function pushPaymentActivity(entries: PaymentAuditTimelineEntry[], payment: Payment) {
  const method = METHOD_LABELS[payment.payment_method] ?? payment.payment_method
  const credyxForceConfirmed =
    payment.status === 'confirmed' && payment.client_confirmed_by === CREDYX_FORCE_CONFIRM_ACTOR
  let detail = `${formatCurrency(payment.amount)} · ${method}`
  if (payment.payment_reference) detail += ` · Ref ${payment.payment_reference}`
  if (payment.notes) detail += ` — ${payment.notes}`

  // Show the funds post event — not current status as a fake "confirmed" history item.
  // Client/Credyx confirmation is covered by payment notes (Payment Confirmation, etc.).
  let title: string
  let source: PaymentAuditSource =
    payment.posted_source === 'client' ? 'carrier' : 'credyx'
  if (credyxForceConfirmed) {
    title =
      payment.payment_kind === 'short'
        ? 'Credyx confirmed correction'
        : 'Credyx closed invoice'
    source = 'credyx'
  } else if (payment.status === 'pending') {
    title = 'Payment Pending'
  } else if (payment.status === 'rejected') {
    title = 'Payment Rejected'
  } else if (payment.status === 'reversed') {
    title = 'Payment Reversed'
  } else if (payment.status === 'disputed') {
    title = 'Payment Disputed'
  } else if (payment.payment_kind === 'short') {
    title = 'Short Correction Posted'
  } else {
    title = 'Payment Posted'
  }

  entries.push({
    id: `payment-${payment.id}`,
    timestamp: payment.received_date || payment.payment_date,
    title,
    detail,
    tone: paymentTone(payment.status),
    kind: 'activity',
    noteKind: 'payment',
    source,
  })

  if (payment.moved_from_payment_id) {
    const source = getPaymentById(payment.moved_from_payment_id)
    entries.push({
      id: `move-in-${payment.id}`,
      timestamp: payment.received_date || payment.payment_date,
      title: 'Funds posted from another invoice',
      detail: source
        ? `${formatCurrency(payment.amount)} moved from ${source.invoice_number}${
            source.load_number ? ` (load ${source.load_number})` : ''
          }`
        : `${formatCurrency(payment.amount)} transferred from another invoice`,
      tone: 'success',
      kind: 'activity',
      noteKind: 'payment',
      source: 'credyx',
    })
  }

  if (payment.reversal_reason) {
    entries.push({
      id: `reversal-${payment.id}`,
      timestamp: payment.reversed_at || payment.received_date,
      title: payment.reversal_type === 'moved' ? 'Funds moved out' : 'Payment reversed',
      detail: payment.reversal_reason,
      tone: 'warning',
      kind: 'activity',
      noteKind: 'payment',
      source: 'credyx',
    })
  }

  if (payment.moved_to_payment_id) {
    const target = getPaymentById(payment.moved_to_payment_id)
    entries.push({
      id: `move-out-${payment.id}`,
      timestamp: payment.reversed_at || payment.received_date,
      title: 'Funds moved to another invoice',
      detail: target
        ? `${formatCurrency(payment.amount)} moved to ${target.invoice_number}${
            target.load_number ? ` (load ${target.load_number})` : ''
          }`
        : `${formatCurrency(payment.amount)} moved to another invoice`,
      tone: 'warning',
      kind: 'activity',
      noteKind: 'payment',
      source: 'credyx',
    })
  }

  if (payment.dispute) {
    const reasonLabel = payment.dispute.reason
      ? getPaymentReceiptDisputeLabel(payment.dispute.reason)
      : undefined
    const openDetail = reasonLabel
      ? `${reasonLabel} — ${payment.dispute.description}`
      : payment.dispute.description

    entries.push({
      id: `dispute-open-${payment.id}`,
      timestamp: payment.dispute.created_at,
      title: 'Payment Dispute',
      detail: openDetail,
      tone: 'warning',
      kind: 'activity',
      noteKind: 'dispute',
      source: 'carrier',
      meta: payment.dispute.created_by?.trim() || undefined,
    })
    if (payment.dispute.response) {
      entries.push({
        id: `dispute-resolved-${payment.id}`,
        timestamp: payment.dispute.resolved_at || payment.dispute.created_at,
        title: 'Dispute Resolved',
        detail: payment.dispute.response,
        tone: 'info',
        kind: 'activity',
        noteKind: 'dispute',
        source: 'credyx',
        meta: payment.dispute.resolved_by?.trim() || undefined,
      })
    }
  }

  if (payment.rejection_reason) {
    entries.push({
      id: `reject-${payment.id}`,
      timestamp: payment.received_date,
      title: 'Payment rejected',
      detail: payment.rejection_reason,
      tone: 'error',
      kind: 'activity',
      noteKind: 'rejection',
      source: 'credyx',
    })
  }
}

function pushAuditLog(entries: PaymentAuditTimelineEntry[], log: AuditLog) {
  const closeType = log.metadata?.close_type
  const isWriteOffRequest = closeType === 'write_off_requested'
  const isWriteOffResolved =
    closeType === 'written_off' || closeType === 'write_off_denied'

  // Prefer dedicated Write-off title over author name for write-off audit rows.
  if (isWriteOffRequest || isWriteOffResolved) {
    const shortfall =
      typeof log.metadata?.shortfall === 'number'
        ? formatCurrency(log.metadata.shortfall)
        : null
    entries.push({
      id: `audit-${log.id}`,
      timestamp: log.timestamp,
      title: isWriteOffRequest ? 'Write-off' : closeType === 'write_off_denied' ? 'Write-off Denied' : 'Write-off Approved',
      detail: isWriteOffRequest
        ? shortfall
          ? `${shortfall} balance written off`
          : log.description
        : log.description,
      tone: closeType === 'write_off_denied' ? 'error' : 'warning',
      kind: 'activity',
      noteKind: 'payment',
      source: isWriteOffRequest ? 'carrier' : 'credyx',
      meta: log.user_name?.trim() || undefined,
    })
    return
  }

  entries.push({
    id: `audit-${log.id}`,
    timestamp: log.timestamp,
    title: log.user_name || 'System',
    detail: log.description,
    tone:
      log.severity === 'error' ? 'error' : log.severity === 'warning' ? 'warning' : 'neutral',
    kind: 'activity',
    noteKind: 'audit',
    source: 'credyx',
  })
}

/**
 * Unified invoice + payment activity feed for the client payment confirmation panel.
 * Free-text notes match InvoiceDetailPanel (getInvoiceNoteEntries + note/client_note only).
 */
export function buildClientPaymentAuditTimeline(
  invoice: Invoice,
  invoicePayments: Payment[],
  focusPaymentId?: string
): PaymentAuditTimelineEntry[] {
  const entries: PaymentAuditTimelineEntry[] = []

  // Same note entries / fallbacks as invoice details.
  getClientInvoiceNoteEntries(invoice).forEach((note) => pushInvoiceNote(entries, note))

  // Open invoice disputes (Activity) — same as InvoiceDetailPanel.
  for (const dispute of getOpenDisputes(invoice)) {
    entries.push({
      id: `invoice-dispute-${dispute.id}`,
      timestamp: dispute.created_at,
      title: getDisputeReasonLabel(dispute.reason),
      detail: dispute.description,
      tone: 'error',
      kind: 'activity',
      noteKind: 'dispute',
      source: 'carrier',
      meta: dispute.response?.trim()
        ? `Credyx response · ${dispute.response}`
        : dispute.created_by?.trim() || undefined,
    })
  }

  invoicePayments.forEach((payment) => pushPaymentActivity(entries, payment))

  const paymentIds = new Set(invoicePayments.map((p) => p.id))
  if (focusPaymentId) paymentIds.add(focusPaymentId)

  // Skip audit rows that restate payment receipt / dispute lifecycle (already on payment).
  const redundantAuditActions = new Set([
    'receipt_disputed',
    'receipt_confirmed',
    'receipt_dispute_requeued',
    'receipt_dispute_rejected',
  ])

  // When a write-off note already exists, skip the duplicate "requested write-off" audit.
  const hasWriteOffNote = entries.some(
    (e) => e.title === 'Write-off' || e.id.endsWith('-writeoff')
  )

  getAllAuditLogs()
    .filter(
      (log) =>
        log.entity_id === invoice.id ||
        (typeof log.metadata?.payment_id === 'string' &&
          paymentIds.has(log.metadata.payment_id))
    )
    .filter((log) => {
      const action = log.metadata?.action
      if (typeof action === 'string' && redundantAuditActions.has(action)) return false
      if (hasWriteOffNote && log.metadata?.close_type === 'write_off_requested') return false
      return true
    })
    .forEach((log) => pushAuditLog(entries, log))

  const seen = new Set<string>()
  return entries
    .filter((entry) => {
      if (seen.has(entry.id)) return false
      seen.add(entry.id)
      return true
    })
    .sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime())
}
